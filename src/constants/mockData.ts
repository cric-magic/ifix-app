function generateSchedule(_id: string, totalAmount: number, periods: number): ScheduleItem[] {
  const principal = Math.round(totalAmount / periods)
  const interest = Math.round(principal * 0.015)
  return Array.from({ length: periods }, (_, i) => {
    const periodNum = i + 1
    const isPast = periodNum <= Math.floor(periods / 2)
    const isNearDue = periodNum === Math.floor(periods / 2) + 1
    return {
      period: periodNum,
      dueDate: `2024-${String(periodNum).padStart(2, '0')}-15`,
      principal,
      interest,
      totalInstallment: principal + interest,
      paidDate: isPast ? `2024-${String(periodNum).padStart(2, '0')}-14` : null,
      status: isPast ? 'paid' : isNearDue ? 'due' : 'future',
    } as ScheduleItem
  })
}

